"""Generate the Easy Channel window layouts. Edit the palette or layout here, then run this script.

The palette, helpers, toolbar, groups and managers are also used by generate_m3u_movies_skin.py.
"""

import os

TOOLS = os.path.dirname(os.path.abspath(__file__))
# Add-on whose strings the $ADDON labels use. Set by the generator that imports this module.
ADDON_ID = "script.m3u.channels"
GENERATOR = "generate_m3u_channels_skin.py"


def skin_folder(addon_id):
    return os.path.join(TOOLS, "..", addon_id, "resources", "skins", "default", "1080i")

BG = "FF0E0F11"        # window background
SURFACE = "FF17181B"   # panels
RAISED = "FF222328"    # selected item without focus, buttons, logo tiles
RAISED2 = "FF2C2D33"   # channel row while one of its buttons is selected
FOCUS = "FFF4F4F5"     # focused item
ON_FOCUS = "FF0E0F11"  # text and icons on the focused item
ON_FOCUS2 = "FF55575E" # secondary text on the focused item
TEXT = "FFF4F4F5"
TEXT2 = "FF9C9EA6"
TEXT3 = "FF62656D"
ACCENT = "FF3B8BFF"
STAR = "FFFFC53D"
DANGER = "FFE5484D"

def visible(condition):
    return f"\n  <visible>{condition}</visible>" if condition else ""

def image(left, top, width, height, texture, color=None, condition=None, border=None, keep=False, fallback=None):
    attrs = (f' border="{border}"' if border else "") + (f' colordiffuse="{color}"' if color else "") + (f' fallback="{fallback}"' if fallback else "")
    aspect = "\n  <aspectratio>keep</aspectratio>" if keep else ""
    return f"""<control type="image">
  <left>{left}</left>
  <top>{top}</top>
  <width>{width}</width>
  <height>{height}</height>{aspect}
  <texture{attrs}>{texture}</texture>{visible(condition)}
</control>"""

def panel(left, top, width, height, color, condition=None):
    return image(left, top, width, height, "panel.png", color, condition, border=16)

def label(left, top, width, height, text, font, color, condition=None, align=None, center=True, scroll=False, control_id=None, wrap=False):
    extra = ""
    if align:
        extra += f"\n  <align>{align}</align>"
    if center:
        extra += "\n  <aligny>center</aligny>"
    if scroll:
        extra += "\n  <scroll>true</scroll>"
    if wrap:
        extra += "\n  <wrapmultiline>true</wrapmultiline>"
    ident = f' id="{control_id}"' if control_id else ""
    body = f"\n  <label>{text}</label>" if text else ""
    return f"""<control type="label"{ident}>
  <left>{left}</left>
  <top>{top}</top>
  <width>{width}</width>
  <height>{height}</height>{extra}
  <font>{font}</font>
  <textcolor>{color}</textcolor>{body}{visible(condition)}
</control>"""

def textbox(left, top, width, height, text, font, color):
    return f"""<control type="textbox">
  <left>{left}</left>
  <top>{top}</top>
  <width>{width}</width>
  <height>{height}</height>
  <font>{font}</font>
  <textcolor>{color}</textcolor>
  <label>{text}</label>
</control>"""

def indent(text, spaces):
    return "\n".join(" " * spaces + line if line else line for line in text.split("\n"))

def join(*controls, spaces=8):
    return "\n".join(indent(control, spaces) for control in controls)

def button(control_id, left, width, onleft, onright, string_id):
    return f"""<control type="button" id="{control_id}">
  <left>{left}</left>
  <top>840</top>
  <width>{width}</width>
  <height>76</height>
  <onup>100</onup>
  <onleft>{onleft}</onleft>
  <onright>{onright}</onright>
  <font>font13</font>
  <align>center</align>
  <aligny>center</aligny>
  <textcolor>{TEXT}</textcolor>
  <focusedcolor>{ON_FOCUS}</focusedcolor>
  <texturefocus border="16" colordiffuse="{FOCUS}">panel.png</texturefocus>
  <texturenofocus border="16" colordiffuse="{RAISED}">panel.png</texturenofocus>
  <label>$ADDON[{ADDON_ID} {string_id}]</label>
</control>"""

def window(comment, default, controls, always=False):
    attr = ' always="true"' if always else ""
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- {comment} Generated by tools/{GENERATOR}. -->
<window>
  <defaultcontrol{attr}>{default}</defaultcontrol>
  <controls>
{indent(controls, 4)}
  </controls>
</window>
"""

