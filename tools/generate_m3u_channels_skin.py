# Modal managers --------------------------------------------------------------

def manager(comment, icon, title_id, item_icon, buttons):
    focus = has(100)
    item = lambda name, detail, icon_color, condition=None, scroll=False: [
        image(18, 20, 52, 52, item_icon, icon_color, condition),
        label(90, 8, 930, 44, "$INFO[ListItem.Label]", "font13", name, condition),
        label(90, 48, 930, 34, "$INFO[ListItem.Label2]", "font12", detail, condition, scroll=scroll)]
    lists = f"""<control type="list" id="100">
  <left>440</left>
  <top>250</top>
  <width>1040</width>
  <height>560</height>
  <ondown>201</ondown>
  <onleft>noop</onleft>
  <onright>noop</onright>
  <scrolltime>120</scrolltime>
  <itemlayout height="92">
{join(*item(TEXT, TEXT2, TEXT2), spaces=4)}
  </itemlayout>
  <focusedlayout height="92">
{join(panel(0, 2, 1040, 88, FOCUS, focus), *item(ON_FOCUS, ON_FOCUS2, ON_FOCUS, focus, True), *item(TEXT, TEXT2, TEXT2, "!" + focus), spaces=4)}
  </focusedlayout>
</control>"""
    controls = join(
        image(0, 0, 1920, 1080, "white.png", "D9000000"),
        panel(410, 130, 1100, 820, SURFACE),
        image(446, 166, 56, 56, icon, ACCENT),
        label(524, 164, 950, 60, f"$ADDON[{ADDON_ID} {title_id}]", "font32_title", TEXT),
        label(460, 330, 1000, 200, "", "font13", TEXT2, align="center", center=False, control_id=300, wrap=True),
        lists, *buttons, spaces=0)
    return window(comment, 201, controls, always=True)

def main():
    channel_focus = has(300)
    row = channel_focus + " + String.IsEmpty(Window.Property(row_action))"
    action = lambda name: channel_focus + " + String.IsEqual(Window.Property(row_action),%s)" % name
    favorite = "String.IsEqual(ListItem.Property(favorite),true)"

    def channel_texts(number, name, detail, condition=None, scroll=False, width=400):
        return [label(12, 0, 64, 90, "$INFO[ListItem.Property(number)]", "font12", number, condition, align="center"),
                label(214, 10, width, 40, "$INFO[ListItem.Label]", "font13", name, condition, scroll=scroll),
                label(214, 48, width, 32, "$INFO[ListItem.Label2]", "font12", detail, condition)]

    def logo(tile):
        return [panel(88, 11, 110, 68, tile), image(96, 16, 94, 58, "$INFO[ListItem.Icon]", keep=True, fallback="tv.png")]

    def row_button(left, name, icon_controls, focus_color):
        on = action(name)
        return [panel(left, 13, 64, 64, focus_color, on)] + icon_controls(on)

    def star_icons(on):
        off = channel_focus + " + ![" + on + "]"
        return [
            # Selected button: dark icon on the light button.
            image(568, 25, 40, 40, "star.png", ON_FOCUS, on + " + " + favorite),
            image(568, 25, 40, 40, "star-outline.png", ON_FOCUS, on + " + !" + favorite),
            # Row focused: dark icons on the light row.
            image(568, 25, 40, 40, "star.png", ON_FOCUS, row + " + " + favorite),
            image(568, 25, 40, 40, "star-outline.png", ON_FOCUS, row + " + !" + favorite),
            # Another button selected: light icons on the raised row.
            image(568, 25, 40, 40, "star.png", STAR, off + " + !String.IsEmpty(Window.Property(row_action)) + " + favorite),
            image(568, 25, 40, 40, "star-outline.png", TEXT2, off + " + !String.IsEmpty(Window.Property(row_action)) + !" + favorite),
        ]

    def trash_icons(on):
        off = channel_focus + " + ![" + on + "]"
        return [image(640, 25, 40, 40, "trash.png", TEXT, on),
                image(640, 25, 40, 40, "trash.png", ON_FOCUS, row),
                image(640, 25, 40, 40, "trash.png", TEXT2, off + " + !String.IsEmpty(Window.Property(row_action))")]

    channels = f"""<!-- Right moves from the channel to its favorite and remove buttons, tracked in Window.Property(row_action). -->
<control type="list" id="300">
  <left>590</left>
  <top>220</top>
  <width>700</width>
  <height>810</height>
  <onup>100</onup>
  <onleft>noop</onleft>
  <onright>noop</onright>
  <scrolltime>120</scrolltime>
  <itemlayout height="90">
{join(*channel_texts(TEXT3, TEXT, TEXT2), *logo(RAISED), image(630, 29, 32, 32, "star.png", STAR, favorite), spaces=4)}
  </itemlayout>
  <focusedlayout height="90">
{join(panel(0, 2, 700, 86, FOCUS, row), panel(0, 2, 700, 86, RAISED2, channel_focus + " + ![" + row + "]"),
      panel(0, 2, 700, 86, RAISED, "!" + channel_focus),
      *logo(RAISED),
      *channel_texts(ON_FOCUS2, ON_FOCUS, ON_FOCUS2, row, True, 330),
      *channel_texts(TEXT2, TEXT, TEXT2, channel_focus + " + ![" + row + "]", False, 330),
      *channel_texts(TEXT2, TEXT, TEXT2, "!" + channel_focus),
      *row_button(556, "favorite", star_icons, FOCUS),
      *row_button(628, "remove", trash_icons, DANGER),
      image(630, 29, 32, 32, "star.png", STAR, "!" + channel_focus + " + " + favorite), spaces=4)}
  </focusedlayout>
</control>"""

    main = join(
        image(0, 0, 1920, 1080, "white.png", BG),
        image(56, 30, 56, 56, "logo.png"),
        label(128, 28, 900, 60, f"$ADDON[{ADDON_ID} 30050]", "font32_title", TEXT),
        label(1360, 28, 500, 60, "$INFO[System.Time]", "font32_title", TEXT2, align="right"),
        "<!-- Toolbar. Tools are added from Python, see TOOLS in gui.py. -->",
        toolbar,
        label(44, 212, 516, 36, "$INFO[Container(100).ListItem.Label]", "font12", ACCENT, tool_focus),
        "<!-- Groups -->",
        panel(40, 256, 520, 784, SURFACE),
        groups,
        "<!-- Channels, with the group name and channel count in the list header -->",
        panel(580, 110, 720, 930, SURFACE),
        label(612, 118, 470, 80, "", "font32_title", TEXT, control_id=401),
        label(1090, 118, 180, 80, "", "font12", TEXT2, align="right", control_id=402),
        image(604, 198, 672, 2, "white.png", RAISED),
        label(620, 260, 640, 300, "", "font13", TEXT2, align="center", center=False, control_id=403, wrap=True),
        channels,
        "<!-- Preview and details of the focused channel. Right after the remove button focuses the preview (500). -->",
        panel(1312, 102, 576, 331, ACCENT, has(500)),
        panel(1320, 110, 560, 315, SURFACE),
        f"""<control type="videowindow">
  <left>1320</left>
  <top>110</top>
  <width>560</width>
  <height>315</height>
  <visible>Player.HasVideo</visible>
</control>""",
        f"""<control type="button" id="500">
  <left>1320</left>
  <top>110</top>
  <width>560</width>
  <height>315</height>
  <onup>noop</onup>
  <ondown>noop</ondown>
  <onleft>noop</onleft>
  <onright>noop</onright>
  <texturefocus>-</texturefocus>
  <texturenofocus>-</texturenofocus>
  <visible>Player.HasVideo</visible>
</control>""",
        image(1400, 150, 400, 235, "$INFO[Container(300).ListItem.Icon]", keep=True, fallback="tv.png",
              condition="!Player.HasVideo + !String.IsEmpty(Container(300).ListItem.Label)"),
        image(1320, 452, 12, 12, "panel.png", ACCENT, "Player.HasVideo"),
        label(1344, 440, 536, 36, f"$ADDON[{ADDON_ID} 30052]: $INFO[VideoPlayer.Title]", "font12", ACCENT, "Player.HasVideo"),
        textbox(1320, 490, 560, 120, "$INFO[Container(300).ListItem.Label]", "font32_title", TEXT),
        label(1320, 620, 560, 40, "$INFO[Container(300).ListItem.Property(group)]", "font13", ACCENT),
        label(1320, 664, 560, 36, "$INFO[Container(300).ListItem.Label2]", "font12", TEXT2),
        label(1320, 924, 560, 116, f"$ADDON[{ADDON_ID} 30051]", "font12", TEXT3, "!" + has(500), center=False, wrap=True),
        label(1320, 924, 560, 116, f"$ADDON[{ADDON_ID} 30107]", "font12", TEXT3, has(500), center=False, wrap=True),
        spaces=0)

    files = {
        "script-m3u-channels-player.xml": window("TV player: full screen video with the channel bar of a TV box.", 100, player_screen()),
        "script-m3u-channels-main.xml": window("Main screen: toolbar and groups on the left, channels in the middle, preview on the right.", 200, main),
        "script-m3u-channels-manager.xml": manager("Modal list manager opened from the gear icon.", "gear.png", 30060, "tv.png",
            [button(201, 440, 248, 203, 204, 30000), button(204, 704, 248, 201, 202, 30093),
             button(202, 968, 248, 204, 203, 30062), button(203, 1232, 248, 202, 201, 30063)]),
        "script-m3u-channels-repos.xml": manager("Modal GitHub repository manager opened from the list manager.", "search.png", 30075, "search.png",
            [button(201, 440, 512, 203, 203, 30076), button(203, 968, 512, 201, 201, 30063)]),
    }
    for name, content in files.items():
        with open(os.path.join(skin_folder(ADDON_ID), name), "w") as output:
            output.write(content)


